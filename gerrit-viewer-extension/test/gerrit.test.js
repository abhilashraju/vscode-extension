const assert = require('assert');
const http = require('http');
const Module = require('module');

const { parseDiff } = require('../src/gerritDiff');
const GerritService = require('../src/gerritService');

const REV = 'a'.repeat(40);
const lines = (n, p = 'l') => Array.from({ length: n }, (_, i) => `${p}${i + 1}`);

// ---------- diff parser ----------
function testParser() {
    // 10 common lines, one changed line, 10 common lines: long stretches collapse to 3 lines of context
    const { rows, truncated } = parseDiff([
        { ab: lines(10) },
        { a: ['old'], b: ['new'] },
        { ab: lines(10, 'm') }
    ]);
    assert.strictEqual(truncated, false);
    assert.deepStrictEqual(rows, [
        { t: 's', count: 7 },
        { t: 'c', o: 8, n: 8, text: 'l8' },
        { t: 'c', o: 9, n: 9, text: 'l9' },
        { t: 'c', o: 10, n: 10, text: 'l10' },
        { t: 'd', o: 11, text: 'old' },
        { t: 'a', n: 11, text: 'new' },
        { t: 'c', o: 12, n: 12, text: 'm1' },
        { t: 'c', o: 13, n: 13, text: 'm2' },
        { t: 'c', o: 14, n: 14, text: 'm3' },
        { t: 's', count: 7 }
    ]);

    // line numbers stay right when old and new sides differ in length
    const d = parseDiff([{ a: ['x', 'y'], b: ['z'] }, { ab: ['t'] }]).rows;
    assert.deepStrictEqual(d, [
        { t: 'd', o: 1, text: 'x' }, { t: 'd', o: 2, text: 'y' }, { t: 'a', n: 1, text: 'z' },
        { t: 'c', o: 3, n: 2, text: 't' }
    ]);

    // server-side skip blocks advance both counters
    const s = parseDiff([{ skip: 40 }, { ab: ['t'] }, { b: ['n'] }]).rows;
    assert.deepStrictEqual(s, [{ t: 's', count: 40 }, { t: 'c', o: 41, n: 41, text: 't' }, { t: 'a', n: 42, text: 'n' }]);

    // short common stretches are kept whole
    assert.strictEqual(parseDiff([{ ab: lines(3) }, { b: ['n'] }, { ab: lines(3) }]).rows.filter((r) => r.t === 's').length, 0);

    // junk input and truncation
    assert.deepStrictEqual(parseDiff(undefined), { rows: [], truncated: false });
    assert.deepStrictEqual(parseDiff([null, 5, {}]).rows, []);
    const cut = parseDiff([{ b: lines(10) }], 4);
    assert.strictEqual(cut.rows.length, 4);
    assert.strictEqual(cut.truncated, true);
    console.log('ok - diff parser');
}

// ---------- API layer against a mock Gerrit ----------
function mockGerrit() {
    const seen = [];
    const detail = {
        _number: 5, project: 'openbmc/bmcweb', branch: 'master', subject: 'Fix <b>it</b>', status: 'NEW', topic: 't',
        owner: { name: 'alice' }, created: '2026-01-01 00:00:00.000000000', updated: '2026-01-02 00:00:00.000000000',
        insertions: 3, deletions: 1, unresolved_comment_count: 1, current_revision: REV,
        revisions: { [REV]: { _number: 2, commit: { message: 'Fix it\n\nBody <script>' } } },
        labels: {
            'Code-Review': { all: [{ name: 'bob', value: 2 }, { name: 'zed', value: 0 }] },
            Verified: { all: [{ username: 'ci', value: -1 }] }
        },
        messages: [{ author: { name: 'ci' }, message: 'built', date: '2026-01-01 05:00:00.000000000', _revision_number: 2, tag: 'autogenerated:ci' }]
    };
    const files = {
        '/COMMIT_MSG': { status: 'A', lines_inserted: 5 },
        '/MERGE_LIST': { status: 'A' },
        'a.c': { lines_inserted: 2, lines_deleted: 1 },
        'new.c': { status: 'R', old_path: 'old.c' },
        'img/logo.png': { status: 'A', binary: true }
    };
    const comments = {
        'a.c': [
            { id: 'c1', patch_set: 2, line: 1, message: 'nit', updated: '2026-01-01 02:00:00.000000000', author: { name: 'dave' }, unresolved: true },
            { id: 'c2', in_reply_to: 'c1', patch_set: 2, line: 1, message: 'done', updated: '2026-01-01 03:00:00.000000000', author: { name: 'alice' }, unresolved: false },
            { id: 'c3', patch_set: 2, line: 2, side: 'PARENT', message: 'why', updated: '2026-01-01 01:00:00.000000000', author: { name: 'erin' }, unresolved: true }
        ],
        '/PATCHSET_LEVEL': [{ id: 'p1', patch_set: 2, message: 'overall', updated: '2026-01-01 04:00:00.000000000', author: { name: 'dave' } }]
    };
    const routes = {
        '/changes/5/detail': () => detail,
        '/changes/5/revisions/current/files': () => files,
        '/changes/5/comments': () => comments,
        [`/changes/5/revisions/${REV}/files/a.c/diff`]: () => ({ content: [{ ab: ['x'] }, { a: ['o'], b: ['n'] }] }),
        [`/changes/5/revisions/${REV}/files/img/logo.png/diff`]: () => ({ binary: true })
    };
    const server = http.createServer((req, res) => {
        const u = new URL(req.url, 'http://x');
        seen.push({ raw: req.url, path: u.pathname, auth: req.headers.authorization });
        const isAuth = u.pathname.startsWith('/a/');
        if (isAuth && !req.headers.authorization) { res.writeHead(401); res.end('Unauthorized'); return; }
        const route = routes[decodeURIComponent(isAuth ? u.pathname.slice(2) : u.pathname)];
        if (!route) { res.writeHead(404); res.end('Not Found'); return; }
        res.writeHead(200, { 'Content-Type': 'application/json' });
        res.end(")]}'\n" + JSON.stringify(route()));
    });
    return { server, seen };
}

async function testService() {
    const { server, seen } = mockGerrit();
    await new Promise((r) => server.listen(0, '127.0.0.1', r));
    const host = `http://127.0.0.1:${server.address().port}`;

    const anon = new GerritService(host);
    const d = await anon.fetchChangeDetail(5);
    assert.ok(seen.every((s) => !s.path.startsWith('/a/') && s.auth === undefined), 'anonymous calls use no /a/ and no auth');
    assert.strictEqual(d.subject, 'Fix <b>it</b>'); // stays raw text; the page renders with textContent
    assert.strictEqual(d.url, `${host}/c/openbmc/bmcweb/+/5`);
    assert.strictEqual(d.patchSet, 2);
    assert.strictEqual(d.revision, REV);
    assert.strictEqual(d.message, 'Fix it\n\nBody <script>');
    assert.deepStrictEqual(d.votes, [
        { label: 'Code-Review', user: 'bob', value: 2 },
        { label: 'Verified', user: 'ci', value: -1 }
    ]);
    assert.deepStrictEqual(d.files.map((f) => f.path), ['/COMMIT_MSG', 'a.c', 'new.c', 'img/logo.png'], '/MERGE_LIST is hidden');
    assert.strictEqual(d.files[0].label, 'Commit message');
    assert.strictEqual(d.files[2].old, 'old.c');
    assert.strictEqual(d.files[2].status, 'renamed');
    assert.strictEqual(d.files[3].binary, true);
    const ac = d.files[1].comments;
    assert.deepStrictEqual(ac.map((c) => c.body), ['why', 'nit', 'done'], 'sorted by time');
    assert.strictEqual(ac[0].side, 'LEFT');
    assert.strictEqual(ac[1].unresolved, false, 'a replied thread is no longer open');
    assert.strictEqual(ac[0].unresolved, true);
    assert.strictEqual(ac[1].created, '2026-01-01T02:00:00Z');
    assert.strictEqual(d.patchsetComments[0].body, 'overall');
    assert.strictEqual(d.messages[0].auto, true);
    console.log('ok - change detail (anonymous): votes, files, comment threads, patchset comments');

    // Authenticated calls use /a/ and Basic auth
    seen.length = 0;
    const authed = new GerritService(host, 'bob', 'secret');
    await authed.fetchChangeDetail(5);
    assert.ok(seen.length === 3 && seen.every((s) => s.path.startsWith('/a/changes/5/')));
    assert.ok(seen.every((s) => s.auth === 'Basic ' + Buffer.from('bob:secret').toString('base64')));
    console.log('ok - authenticated calls use /a/ and Basic auth');

    // Diffs
    const diff = await anon.fetchFileDiff(5, REV, 'a.c');
    assert.deepStrictEqual(diff.rows, [
        { t: 'c', o: 1, n: 1, text: 'x' }, { t: 'd', o: 2, text: 'o' }, { t: 'a', n: 2, text: 'n' }
    ]);
    const bin = await anon.fetchFileDiff(5, REV, 'img/logo.png');
    assert.deepStrictEqual(bin, { rows: null, truncated: false, binary: true });
    assert.ok(seen.some((s) => s.raw.includes('/files/img%2Flogo.png/diff')), 'path is URL-encoded');
    console.log('ok - file diffs, binary files, path encoding');

    // Errors and input validation
    await assert.rejects(() => anon.fetchChangeDetail(999), /HTTP 404/);
    const before = seen.length;
    await assert.rejects(() => anon.fetchChangeDetail(-1), /Invalid/);
    await assert.rejects(() => anon.fetchChangeDetail('5/../x'), /Invalid/);
    await assert.rejects(() => anon.fetchFileDiff(5, 'current', 'a.c'), /Invalid/);
    await assert.rejects(() => anon.fetchFileDiff(5, REV + '/x', 'a.c'), /Invalid/);
    await assert.rejects(() => anon.fetchFileDiff(5, REV, ''), /Invalid/);
    await assert.rejects(() => anon.fetchFileDiff(5, REV, 'x'.repeat(5000)), /Invalid/);
    assert.strictEqual(seen.length, before, 'bad references never reach the network');
    console.log('ok - errors and input validation');
    server.close();
}

// ---------- webview page script in a minimal DOM ----------
function makeDom() {
    class Node {
        constructor(tag) { this.tag = tag; this.children = []; this.className = ''; this.listeners = {}; this._text = ''; this.open = false; }
        set textContent(v) { this._text = String(v); this.children = []; }
        get textContent() { return this._text + this.children.map((c) => c.textContent).join(''); }
        set innerHTML(v) { this.children = []; this._text = ''; this._html = v; }
        appendChild(c) { this.children.push(c); return c; }
        addEventListener(t, cb) { (this.listeners[t] = this.listeners[t] || []).push(cb); }
        fire(t) { (this.listeners[t] || []).forEach((cb) => cb({ preventDefault() {} })); }
        all(pred, out = []) { if (pred(this)) { out.push(this); } this.children.forEach((c) => c.all(pred, out)); return out; }
    }
    const root = new Node('div');
    const doc = {
        title: '',
        getElementById: () => root,
        createElement: (t) => new Node(t),
        createDocumentFragment: () => new Node('frag')
    };
    return { root, doc };
}

function testPageScript() {
    const { getChangeDetailHtml } = require('../src/changeDetailHtml');
    const html = getChangeDetailHtml({ nonce: 'n', cspSource: 'x' });
    assert.ok(/Content-Security-Policy[^>]*default-src 'none'/.test(html));
    assert.ok(!/unsafe-inline|unsafe-eval/.test(html));
    const js = html.split('<script nonce="n">')[1].split('</script>')[0];

    const { root, doc } = makeDom();
    const posted = [];
    let handler;
    const win = { addEventListener: (t, cb) => { handler = cb; } };
    new Function('acquireVsCodeApi', 'document', 'window', js)(() => ({ postMessage: (m) => posted.push(m) }), doc, win);
    assert.deepStrictEqual(posted[0], { command: 'ready' });

    const c = (over) => Object.assign({ author: 'dave', body: 'b', created: '', patchSet: 2, line: 1, side: 'RIGHT', reply: false, unresolved: false }, over);
    const change = {
        number: 5, project: 'p', branch: 'master', subject: '<img src=x onerror=alert(1)>', status: 'NEW', topic: '', owner: 'alice',
        url: 'https://gerrit.example/c/p/+/5', created: '', updated: '', insertions: 1, deletions: 1, unresolved: 0, patchSet: 2,
        revision: REV, message: '<script>x</script>', votes: [], filesTruncated: false, patchsetComments: [], messages: [],
        files: [
            { path: 'a.c', label: 'a.c', old: '', status: 'modified', ins: 1, del: 1, binary: false, comments: [
                c({ body: 'right-note', line: 1, side: 'RIGHT' }),
                c({ body: 'left-note', line: 1, side: 'LEFT' }),
                c({ body: 'old-patchset-note', patchSet: 1, line: 1 }),
                c({ body: 'offscreen-note', line: 99 })
            ] },
            { path: 'img.png', label: 'img.png', old: '', status: 'added', ins: 0, del: 0, binary: true, comments: [] }
        ]
    };
    handler({ data: { type: 'detail', change } });
    const text = root.textContent;
    assert.ok(text.includes('<img src=x onerror=alert(1)> #5'), 'subject shown as text');
    assert.ok(text.includes('<script>x</script>'), 'commit message shown as text');
    assert.strictEqual(root.all((n) => n.tag === 'img').length, 0);

    const [fileA, fileImg] = root.all((n) => n.tag === 'details');
    assert.strictEqual(fileA.children.length, 2, 'summary + empty body: diff is not requested until the file is opened');
    assert.strictEqual(posted.length, 1);
    fileA.open = true; fileA.fire('toggle');
    fileA.fire('toggle');
    assert.strictEqual(posted.length, 2, 'diff requested once');
    assert.deepStrictEqual(posted[1], { command: 'loadDiff', id: 1, number: 5, revision: REV, path: 'a.c' });

    handler({ data: { type: 'diff', id: 1, result: { binary: false, truncated: false, rows: [
        { t: 'd', o: 1, text: 'old' }, { t: 'a', n: 1, text: 'new' }, { t: 's', count: 5 }
    ] } } });
    assert.strictEqual(fileA.all((n) => /^dl /.test(n.className)).length, 3);
    const body = fileA.textContent;
    assert.ok(body.includes('right-note'), 'comment on the new side shown under the added line');
    assert.ok(body.includes('left-note'), 'comment on the old side shown under the removed line');
    assert.ok(body.includes('old-patchset-note') && body.includes('offscreen-note'), 'unplaceable comments are still listed');
    assert.strictEqual(fileA.all((n) => n.className === 'inline').length, 2, 'only the two placeable comments are inline');
    // a late duplicate answer is ignored
    handler({ data: { type: 'diff', id: 1, result: { binary: false, truncated: false, rows: [{ t: 'a', n: 1, text: 'dup' }] } } });
    assert.ok(!fileA.textContent.includes('dup'));

    fileImg.open = true; fileImg.fire('toggle');
    handler({ data: { type: 'diff', id: 2, result: { rows: null, truncated: false, binary: true } } });
    assert.ok(fileImg.textContent.includes('binary file'));

    // per-file failure
    const { root: r2, doc: d2 } = makeDom();
    let h2;
    new Function('acquireVsCodeApi', 'document', 'window', js)(() => ({ postMessage() {} }), d2, { addEventListener: (t, cb) => { h2 = cb; } });
    h2({ data: { type: 'detail', change } });
    const f2 = r2.all((n) => n.tag === 'details')[0];
    f2.open = true; f2.fire('toggle');
    h2({ data: { type: 'diffError', id: 1, error: 'HTTP 500' } });
    assert.ok(f2.textContent.includes('Error: HTTP 500'));
    console.log('ok - page renders safely, lazy diff, inline comments by side, binary and error states');

    handler({ data: { type: 'error', error: 'HTTP 404' } });
    assert.ok(root.textContent.includes('Error: HTTP 404'));
}

// ---------- panel lifecycle with a mock vscode ----------
async function testPanel() {
    const disposers = [];
    const panels = [];
    const mockVscode = {
        window: { createWebviewPanel: () => {
            const p = { disposed: false, title: '', revealed: 0, posted: [],
                reveal() { if (this.disposed) { throw new Error('Webview is disposed'); } this.revealed++; },
                onDidDispose(cb) { disposers.push(cb); },
                webview: { cspSource: 'x', html: '', onDidReceiveMessage(cb) { p.onMessage = cb; },
                    postMessage(m) { if (p.disposed) { throw new Error('Webview is disposed'); } p.posted.push(m); } } };
            panels.push(p); return p; } },
        ViewColumn: { Active: -1 },
        env: { openExternal: (u) => { mockVscode.opened.push(String(u)); } },
        Uri: { parse: (s) => s },
        opened: []
    };
    const orig = Module._load;
    Module._load = function (r, ...rest) { return r === 'vscode' ? mockVscode : orig.call(this, r, ...rest); };
    const { ChangeDetailPanel } = require('../src/changeDetailPanel');
    Module._load = orig;

    const diffCalls = [];
    const provider = { loadCredentials: async () => {}, gerritService: {
        fetchChangeDetail: async (n) => {
            if (n === 404) { throw new Error('HTTP 404'); }
            return { number: n, project: 'openbmc/bmcweb', url: `https://gerrit.example/c/openbmc/bmcweb/+/${n}`, revision: REV, files: [{ path: 'a.c' }] };
        },
        fetchFileDiff: async (n, rev, path) => { diffCalls.push([n, rev, path]); return { rows: [], truncated: false, binary: false }; }
    } };
    const ctx = { subscriptions: [] };

    ChangeDetailPanel.show(ctx, provider, 5);
    ChangeDetailPanel.show(ctx, provider, 5); // same change: reuse
    assert.strictEqual(panels.length, 1);
    assert.strictEqual(panels[0].revealed, 1);

    panels[0].onMessage({ command: 'ready' });
    await new Promise((r) => setTimeout(r, 20));
    assert.strictEqual(panels[0].posted[0].type, 'detail');
    assert.strictEqual(panels[0].title, '#5 bmcweb');

    // openUrl only for the change's own URL
    panels[0].onMessage({ command: 'openUrl', url: 'https://evil.example/' });
    panels[0].onMessage({ command: 'openUrl', url: 'https://gerrit.example/c/openbmc/bmcweb/+/5' });
    assert.deepStrictEqual(mockVscode.opened, ['https://gerrit.example/c/openbmc/bmcweb/+/5']);

    // loadDiff allow-list
    const ok = { command: 'loadDiff', id: 1, number: 5, revision: REV, path: 'a.c' };
    panels[0].posted.length = 0;
    panels[0].onMessage(Object.assign({}, ok, { path: '../../etc/passwd' }));
    panels[0].onMessage(Object.assign({}, ok, { revision: 'b'.repeat(40) }));
    panels[0].onMessage(Object.assign({}, ok, { number: 6 }));
    panels[0].onMessage(Object.assign({}, ok, { id: 'x' })); // ignored: no id to answer
    panels[0].onMessage({ command: 'bogus' });
    panels[0].onMessage(null);
    await new Promise((r) => setTimeout(r, 20));
    assert.deepStrictEqual(diffCalls, []);
    assert.deepStrictEqual(panels[0].posted.map((m) => m.type), ['diffError', 'diffError', 'diffError']);
    panels[0].onMessage(ok);
    await new Promise((r) => setTimeout(r, 20));
    assert.deepStrictEqual(diffCalls, [[5, REV, 'a.c']]);
    assert.strictEqual(panels[0].posted[3].type, 'diff');
    assert.strictEqual(panels[0].posted[3].id, 1);

    // errors are reported to the page
    ChangeDetailPanel.show(ctx, provider, 404);
    panels[1].onMessage({ command: 'refresh' });
    await new Promise((r) => setTimeout(r, 20));
    assert.deepStrictEqual(panels[1].posted[0], { type: 'error', error: 'HTTP 404' });

    // closing mid-load must not throw, and the change can be reopened
    panels[0].onMessage({ command: 'refresh' });
    panels[0].disposed = true; disposers[0]();
    await new Promise((r) => setTimeout(r, 20));
    ChangeDetailPanel.show(ctx, provider, 5);
    assert.strictEqual(panels.length, 3);
    console.log('ok - panel reuse, URL and diff allow-lists, error path, close during load');
}

